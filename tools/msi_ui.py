"""Native Windows Installer dialogs, with no custom executable bootstrapper."""
from pathlib import Path


def add_ui(table,add,root):
    table('TextStyle','`TextStyle` CHAR(72) NOT NULL, `FaceName` CHAR(32) NOT NULL, `Size` SHORT NOT NULL, `Color` LONG, `StyleBits` SHORT','`TextStyle`')
    add('TextStyle','Normal','Segoe UI',9,0,0)
    add('TextStyle','Heading','Segoe UI',16,0,1)
    add('Property','DefaultUIFont','Normal')
    table('Dialog','`Dialog` CHAR(72) NOT NULL, `HCentering` SHORT NOT NULL, `VCentering` SHORT NOT NULL, `Width` SHORT NOT NULL, `Height` SHORT NOT NULL, `Attributes` LONG, `Title` CHAR(128), `Control_First` CHAR(50) NOT NULL, `Control_Default` CHAR(50), `Control_Cancel` CHAR(50)','`Dialog`')
    table('Control','`Dialog_` CHAR(72) NOT NULL, `Control` CHAR(50) NOT NULL, `Type` CHAR(20) NOT NULL, `X` SHORT NOT NULL, `Y` SHORT NOT NULL, `Width` SHORT NOT NULL, `Height` SHORT NOT NULL, `Attributes` LONG, `Property` CHAR(72), `Text` CHAR(0), `Control_Next` CHAR(50), `Help` CHAR(50)','`Dialog_`, `Control`')
    table('ControlEvent','`Dialog_` CHAR(72) NOT NULL, `Control_` CHAR(50) NOT NULL, `Event` CHAR(50) NOT NULL, `Argument` CHAR(255) NOT NULL, `Condition` CHAR(255), `Ordering` SHORT','`Dialog_`, `Control_`, `Event`, `Argument`, `Condition`')
    table('ControlCondition','`Dialog_` CHAR(72) NOT NULL, `Control_` CHAR(50) NOT NULL, `Action` CHAR(50) NOT NULL, `Condition` CHAR(255) NOT NULL','`Dialog_`, `Control_`, `Action`, `Condition`')
    table('CheckBox','`Property` CHAR(72) NOT NULL, `Value` CHAR(64)','`Property`')
    add('CheckBox','ACCEPTTERMS','1')
    def dialog(name,title,first='Cancel',default='Cancel',height=305,attributes=3):
        add('Dialog',name,50,50,420,height,attributes,title,first,default,'Cancel')
    def control(d,name,kind,x,y,width,height,text=None,prop=None,next=None,attrs=3):
        add('Control',d,name,kind,x,y,width,height,attrs,prop,text,next,None)
    def event(d,control,event,arg,condition='1',order=1):add('ControlEvent',d,control,event,arg,condition,order)
    terms=(root/'app/TERMS.txt').read_text(encoding='utf-8')
    rtf=r'{\rtf1\ansi\deff0{\fonttbl{\f0 Segoe UI;}}\f0\fs18 '+terms.replace('\\','\\\\').replace('{',r'\{').replace('}',r'\}').replace('\n',r'\par ')+'}'
    dialog('SetupDlg','Repaintko installieren','Terms','Install')
    control('SetupDlg','Title','Text',18,12,380,24,r'{\Heading}Willkommen bei Repaintko')
    control('SetupDlg','Terms','ScrollableText',18,44,384,135,rtf,next='Accept')
    control('SetupDlg','Accept','CheckBox',18,185,380,18,'Ich akzeptiere die Nutzungsbedingungen.',prop='ACCEPTTERMS',next='Path')
    control('SetupDlg','FolderLabel','Text',18,211,370,13,'Installationsordner:')
    control('SetupDlg','Path','PathEdit',18,228,293,20,prop='INSTALLDIR',next='Browse')
    control('SetupDlg','Browse','PushButton',319,228,83,20,'Durchsuchen ...',next='Install')
    control('SetupDlg','Install','PushButton',238,270,80,22,'Installieren',next='Cancel',attrs=1)
    control('SetupDlg','Cancel','PushButton',326,270,76,22,'Abbrechen',next='Terms')
    add('ControlCondition','SetupDlg','Install','Enable','ACCEPTTERMS = "1"')
    add('ControlCondition','SetupDlg','Install','Disable','ACCEPTTERMS <> "1"')
    event('SetupDlg','Browse','SpawnDialog','FolderDlg')
    event('SetupDlg','Install','SetTargetPath','INSTALLDIR','ACCEPTTERMS = "1"',1)
    event('SetupDlg','Install','EndDialog','Return','ACCEPTTERMS = "1"',2)
    event('SetupDlg','Cancel','EndDialog','Exit')
    dialog('FolderDlg','Installationsordner auswählen','Path','Choose',height=280)
    control('FolderDlg','Label','Text',18,15,380,18,'Ordner auswählen oder einen vollständigen Pfad eingeben:')
    control('FolderDlg','Combo','DirectoryCombo',18,40,384,60,prop='INSTALLDIR',next='List',attrs=131075)
    control('FolderDlg','List','DirectoryList',18,66,384,125,prop='INSTALLDIR',next='Path')
    control('FolderDlg','Path','PathEdit',18,201,384,20,prop='INSTALLDIR',next='Choose')
    control('FolderDlg','Choose','PushButton',238,240,80,22,'Übernehmen',next='Cancel')
    control('FolderDlg','Cancel','PushButton',326,240,76,22,'Zurück',next='Combo')
    event('FolderDlg','Choose','SetTargetPath','INSTALLDIR',order=1)
    event('FolderDlg','Choose','EndDialog','Return',order=2)
    event('FolderDlg','Cancel','EndDialog','Return')
    for name,upgrade in [('MaintenanceDlg',False),('UpgradeDlg',True)]:
        dialog(name,'Repaintko - Wartung','Repair','Repair',height=190)
        control(name,'Title','Text',18,15,384,28,r'{\Heading}Repaintko ist bereits installiert')
        text=('Eine ältere Version ist vorhanden. Reparieren / Aktualisieren installiert diese Version und stellt Programmdateien sowie Verknüpfungen wieder her.' if upgrade else
              'Reparieren stellt fehlende oder beschädigte Programmdateien und Verknüpfungen wieder her. Deine separat gespeicherten Bilder und Projekte bleiben erhalten.')
        control(name,'Info','Text',18,52,384,68,text)
        control(name,'Repair','PushButton',18,145,190,24,'Reparieren / Aktualisieren' if upgrade else 'Reparieren',next='Cancel')
        control(name,'Cancel','PushButton',320,145,82,24,'Abbrechen',next='Repair')
        if not upgrade:
            event(name,'Repair','[REINSTALL]','ALL',order=1)
            event(name,'Repair','[REINSTALLMODE]','amus',order=2)
        event(name,'Repair','EndDialog','Return',order=3)
        event(name,'Cancel','EndDialog','Exit')
    dialog('ProgressDlg','Repaintko - Installation',height=145,attributes=1)
    control('ProgressDlg','Title','Text',18,18,384,30,r'{\Heading}Repaintko wird eingerichtet')
    control('ProgressDlg','Info','Text',18,57,384,25,'Bitte warten. Windows verarbeitet die Programmdateien.')
    control('ProgressDlg','Bar','ProgressBar',18,91,280,15,attrs=65537)
    control('ProgressDlg','Cancel','PushButton',320,87,82,24,'Abbrechen')
    event('ProgressDlg','Cancel','EndDialog','Exit')
    table('EventMapping','`Dialog_` CHAR(72) NOT NULL, `Control_` CHAR(50) NOT NULL, `Event` CHAR(50) NOT NULL, `Attribute` CHAR(50) NOT NULL','`Dialog_`, `Control_`, `Event`')
    add('EventMapping','ProgressDlg','Bar','SetProgress','Progress')
    for name,title,message in [('CompleteDlg','Fertig','Repaintko wurde eingerichtet. Du kannst es über das Desktop-Symbol oder das Startmenü öffnen.'),
                               ('FailedDlg','Installation fehlgeschlagen','Windows konnte die Installation nicht abschließen. Prüfe die angezeigte Fehlermeldung und die Administratorberechtigung.')]:
        dialog(name,'Repaintko - '+title,height=160)
        control(name,'Title','Text',18,15,384,28,r'{\Heading}'+title)
        control(name,'Info','Text',18,52,384,55,message)
        control(name,'Cancel','PushButton',320,123,82,24,'Schließen')
        event(name,'Cancel','EndDialog','Return')
